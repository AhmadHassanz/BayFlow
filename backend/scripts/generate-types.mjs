import { spawnSync } from 'node:child_process';
import { mkdir, rename, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';

const backendDirectory = fileURLToPath(new URL('../', import.meta.url));
const destination = fileURLToPath(new URL('../../frontend/src/lib/supabase/database.types.ts', import.meta.url));
const cli = fileURLToPath(new URL('../node_modules/supabase/dist/supabase.js', import.meta.url));
const args = ['gen', 'types', '--lang', 'typescript', '--schema', 'public'];
if (process.env.BAYFLOW_TYPEGEN_DB_URL) {
  const url = new URL(process.env.BAYFLOW_TYPEGEN_DB_URL);
  if (!['localhost', '127.0.0.1', '[::1]'].includes(url.hostname)) {
    throw new Error('This script only accepts a loopback database. Use the CLI directly to generate reviewed Cloud types.');
  }
  args.push('--db-url', url.toString());
} else {
  args.push('--linked');
}
const result = spawnSync(process.execPath, [cli, ...args], {
  cwd: backendDirectory, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'],
});
if (result.error) throw result.error;
if (result.status !== 0 || !result.stdout.includes('export type Database')) {
  process.stderr.write(result.stderr);
  throw new Error('Supabase type generation failed; the existing types were preserved.');
}
await mkdir(new URL('../../frontend/src/lib/supabase/', import.meta.url), { recursive: true });
const source = ts.createSourceFile('database.types.ts', result.stdout, ts.ScriptTarget.Latest, true, ts.ScriptKind.TS);
const formatted = ts.createPrinter({ newLine: ts.NewLineKind.LineFeed }).printFile(source);
await writeFile(`${destination}.tmp`, `// Generated by Supabase CLI and formatted by TypeScript. Do not edit.\n${formatted}`, 'utf8');
await rename(`${destination}.tmp`, destination);
console.log('Generated frontend/src/lib/supabase/database.types.ts using Supabase CLI.');
